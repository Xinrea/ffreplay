func TestEditGameBoard(t *testing.T) {
	board := gameboard.Board{Name: "集合", Background: 2, Objects: []gameboard.Object{
		{Type: 14, Flags: 1, X: 2560, Y: 1920, Scale: 70, RGBA: [4]byte{255, 255, 255, 12}},
		{Type: 27, Flags: 1, X: 512, Y: 128, Scale: 100},
	}}
	code, err := gameboard.Encode(board)
	if err != nil {
		t.Fatal(err)
	}
	p, note, err := ImportGame(code)
	if err != nil || note != "" {
		t.Fatal(err, note)
	}
	s := &p.Steps[0]
	if s.Name != "集合" || s.Objects[0].Kind != "Paladin" || s.Objects[1].Kind != "game-14" || s.Objects[1].X != 0 || s.Objects[1].Y != 0 {
		t.Fatal(s)
	}
	s.Objects[0].X++
	code, err = ExportGame(p, 0)
	if err != nil {
		t.Fatal(err)
	}
	got, err := gameboard.Decode(code)
	board.Objects[1].X += 128
	if err != nil || !reflect.DeepEqual(got, board) {
		t.Fatal(got, err)
	}
}

func TestTetherLifecycle(t *testing.T) {
	e := Editor{Plan: New()}
	s := e.Step()
	s.Objects = []Object{{Kind: "MT", Label: "MT", Radius: 1, X: -4}, {Kind: "ST", Label: "ST", Radius: 1, X: 4}}
	if e.Connect(0, 1, Endpoint{}, Endpoint{}, "+-") < 0 {
		t.Fatal("couldn't create tether")
	}
	e.AddStep(true)
	s = e.Step()
	slices.Reverse(s.Objects)
	s.Objects[1].X = 7
	x, _, _ := s.Position(s.Links[0].Start)
	if x != 7 {
		t.Fatal("tether followed a layer, not an object")
	}
	raw, _ := json.Marshal(e.Plan)
	if _, err := Decode(raw); err != nil {
		t.Fatal(err)
	}
	code, err := ExportGame(e.Plan, 1)
	if err != nil {
		t.Fatal(err)
	}
	board, err := gameboard.Decode(code)
	if err != nil {
		t.Fatal(err)
	}
	line := board.Objects[len(board.Objects)-1]
	if line.Type != 12 || line.X != 3456 || line.Params[0] != 3072 {
		t.Fatal(line)
	}
	e.Checkpoint()
	s.RemoveObject(1)
	if len(s.Links) != 0 || len(e.Steps[0].Links) != 1 {
		t.Fatal("dangling link or shared steps")
	}
	e.History(false)
	if len(e.Step().Links) != 1 {
		t.Fatal("undo failed")
	}
	e.Step().Links[0].Start.ID = 70
	raw, _ = json.Marshal(e.Plan)
	if _, err := Decode(raw); err == nil {
		t.Fatal("accepted dangling tether")
	}
}

func TestIndependentMixedLayerCode(t *testing.T) {
	// Generated by xiv-strat-board 0.2.3, not by this encoder. The line is
	// between the stack marker and the text, not behind every other layer.
	const code = "[stgy:aOr8r962tl6wNTdhs5JfW7EPDE+zHFeiZMezQiL3KoC1Ti0rq5tnyNg6VsVyo+SZPr3RiXQ2J8f8nvy4T4UEeQCFV8Ie0FvyNzdKVduUTBTRCZ5ZTByZXVBacbqINgqhiGaOmoiiScVWPBuWBb7n+45ZIJRx9RydtGM2gYCpYfqc9Y-h7z9Y+]"
	p, _, err := ImportGame(code)
	if err != nil {
		t.Fatal(err)
	}
	s := p.Steps[0]
	if len(s.Links) != 1 || s.Links[0].Above != 1 || s.Objects[0].Label != "集合" {
		t.Fatal(s)
	}
	again, err := ExportGame(p, 0)
	if err != nil {
		t.Fatal(err)
	}
	got, err := gameboard.Decode(again)
	want, _ := gameboard.Decode(code)
	if err != nil || !reflect.DeepEqual(got, want) {
		t.Fatal("wire properties changed", got, want, err)
	}
}
